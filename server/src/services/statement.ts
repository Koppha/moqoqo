/** The statement as one printable A4 HTML page (the table runs over as many pages as it needs). */
export async function statementHtml(q: Queryable, u: UserRow, s: Statement, lang: StatementLang = 'en'): Promise<string> {
  const t = TEXT[lang]
  const branding = await getBranding(q)
  let logo = '<div class="wordmark">EcoCash</div>'
  if (branding.logo) {
    const file = await readAsset(q, branding.logo.id)
    if (file) logo = `<img class="logo" alt="" src="data:${file.contentType};base64,${file.content.toString('base64')}">`
  }
  const m = (cents: number) => esc(formatM(cents))
  const rows = s.lines.map((l) => `<tr>
      <td class="nowrap">${esc(maseruTime(l.at))}</td>
      <td class="ref">${esc(l.reference)}</td>
      <td>${esc(l.description)}</td>
      <td class="num in">${l.cents > 0 ? m(l.cents) : ''}</td>
      <td class="num">${l.cents < 0 ? m(-l.cents) : ''}</td>
      <td class="num bal">${m(l.balanceCents)}</td>
    </tr>`).join('')

  return `<!DOCTYPE html>
<html lang="${lang}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(t.title)} · ${esc(s.from)} ${esc(t.to)} ${esc(s.to)}</title>
<style>
  @page { size: A4; margin: 14mm 12mm 16mm; @bottom-right { content: counter(page) " / " counter(pages); font: 8pt sans-serif; color: #667; } }
  * { box-sizing: border-box; }
  body { margin: 0; font-family: -apple-system, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; font-size: 9pt; color: #1A1D2E; -webkit-print-color-adjust: exact; print-color-adjust: exact; }
  .top { display: flex; justify-content: space-between; align-items: center; background: linear-gradient(135deg, #2446E8, #0B1D86); color: #fff; border-radius: 4mm; padding: 6mm 7mm; }
  .logo { max-height: 11mm; max-width: 50mm; }
  .wordmark { font-size: 20pt; font-weight: 900; font-style: italic; }
  .top h1 { margin: 0; font-size: 15pt; text-align: right; }
  .top .period { font-size: 9pt; opacity: .85; text-align: right; margin-top: 1mm; }
  .holder { display: grid; grid-template-columns: repeat(4, 1fr); gap: 3mm; margin: 5mm 0; }
  .holder div span { display: block; font-size: 7.5pt; color: #667; text-transform: uppercase; letter-spacing: .3pt; }
  .holder div b { font-size: 9.5pt; }
  .summary { display: grid; grid-template-columns: repeat(4, 1fr); gap: 3mm; margin-bottom: 5mm; }
  .summary div { border: 0.3mm solid #DDE3F5; border-radius: 3mm; padding: 3mm 4mm; }
  .summary span { display: block; font-size: 7.5pt; color: #667; }
  .summary b { font-size: 12pt; }
  .summary .closing { background: #EEF2FF; border-color: #2446E8; }
  table { width: 100%; border-collapse: collapse; }
  thead { display: table-header-group; }
  tr { break-inside: avoid; }
  th { text-align: left; font-size: 7.5pt; text-transform: uppercase; letter-spacing: .3pt; color: #fff; background: #0B1D86; padding: 2mm; }
  td { padding: 1.8mm 2mm; border-bottom: 0.2mm solid #E6E9F2; vertical-align: top; }
  tbody tr:nth-child(even) td { background: #F7F8FC; }
  .num { text-align: right; white-space: nowrap; }
  th.num { text-align: right; }
  .in { color: #1D6B3C; }
  .bal { font-weight: 700; }
  .ref { font-family: ui-monospace, Menlo, Consolas, monospace; font-size: 8pt; color: #445; }
  .nowrap { white-space: nowrap; }
  .none { text-align: center; color: #667; padding: 8mm; }
  .foot { margin-top: 6mm; font-size: 7.5pt; color: #667; line-height: 1.5; }
</style></head>
<body>
  <div class="top">${logo}<div><h1>${esc(t.title)}</h1><div class="period">${esc(s.from)} ${esc(t.to)} ${esc(s.to)}</div></div></div>
  <div class="holder">
    <div><span>${esc(t.holder)}</span><b>${esc(displayName(u))}</b></div>
    <div><span>${esc(t.number)}</span><b>${u.msisdn ? esc(u.msisdn) : '—'}</b></div>
    <div><span>${esc(t.username)}</span><b>${u.username ? `@${esc(u.username)}` : '—'}</b></div>
    <div><span>${esc(t.tier)}</span><b>${esc(t.tierName(u.kyc_tier))}</b></div>
  </div>
  <div class="summary">
    <div><span>${esc(t.opening)}</span><b>${m(s.openingCents)}</b></div>
    <div><span>${esc(t.moneyIn)}</span><b class="in">${m(s.inCents)}</b></div>
    <div><span>${esc(t.moneyOut)}</span><b>${m(s.outCents)}</b></div>
    <div class="closing"><span>${esc(t.closing)}</span><b>${m(s.closingCents)}</b></div>
  </div>
  <table>
    <thead><tr><th>${esc(t.date)}</th><th>${esc(t.reference)}</th><th>${esc(t.details)}</th><th class="num">${esc(t.in)}</th><th class="num">${esc(t.out)}</th><th class="num">${esc(t.balance)}</th></tr></thead>
    <tbody>${rows || `<tr><td colspan="6" class="none">${esc(t.none)}</td></tr>`}</tbody>
  </table>
  <div class="foot">${esc(t.generated(maseruTime(new Date())))}<br>${esc(t.queries)}</div>
</body></html>`
}
