// Account statement: every movement on a wallet over a period (Maseru calendar days), with the opening and closing
// balance and a running balance. One A4 HTML document: the apps turn it into a PDF (expo-print), the portal prints it.
import type { Queryable } from '../db/index'
import type { TransactionRow } from '../ecocash/index'
import { validation } from '../errors'
import { formatM } from '../lib/money'
import { getBranding, readAsset } from './branding'
import { esc } from './poster'
import { toTransactions } from './transactions'
import { displayName, type UserRow } from './users'

export type StatementLang = 'en' | 'st'

/** Longest period one statement covers. */
export const STATEMENT_MAX_DAYS = 366
const DAY_MS = 86_400_000

export interface StatementLine { at: Date; reference: string; description: string; cents: number; balanceCents: number }
export interface Statement {
  from: string
  to: string
  openingCents: number
  closingCents: number
  inCents: number
  outCents: number
  lines: StatementLine[]
}

/** Start of a Maseru calendar day (UTC+2, no daylight saving) as a UTC instant. */
const maseruDay = (day: string) => new Date(`${day}T00:00:00+02:00`)
/** "2026-10-19 14:05" in Maseru. */
const maseruTime = (at: Date) => new Date(at.getTime() + 2 * 3_600_000).toISOString().slice(0, 16).replace('T', ' ')
const today = () => maseruTime(new Date()).slice(0, 10)

/** Movements from `from` to `to` (inclusive, Maseru days). Balances are worked back from the wallet's balance now. */
export async function buildStatement(q: Queryable, u: UserRow, from: string, to: string): Promise<Statement> {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(from) || !/^\d{4}-\d{2}-\d{2}$/.test(to) || Number.isNaN(maseruDay(from).getTime()) || Number.isNaN(maseruDay(to).getTime())) {
    throw validation('from and to must be dates like 2026-10-01')
  }
  if (from > to) throw validation('The start date must be on or before the end date')
  if (to > today()) throw validation('The end date cannot be in the future')
  const start = maseruDay(from)
  const end = new Date(maseruDay(to).getTime() + DAY_MS)
  if ((end.getTime() - start.getTime()) / DAY_MS > STATEMENT_MAX_DAYS) throw validation(`A statement covers at most ${STATEMENT_MAX_DAYS} days`)

  // Money in counts positive, out negative (from this wallet's side).
  const signed = `CASE WHEN to_user_id = $1 THEN amount_cents ELSE -amount_cents END`
  const [{ after }] = await q.query<{ after: string | number }>(
    `SELECT COALESCE(sum(${signed}), 0) AS after FROM transactions WHERE (from_user_id = $1 OR to_user_id = $1) AND created_at >= $2`,
    [u.id, end],
  )
  const rows = await q.query<TransactionRow>(
    `SELECT * FROM transactions WHERE (from_user_id = $1 OR to_user_id = $1) AND created_at >= $2 AND created_at < $3
     ORDER BY created_at, id`,
    [u.id, start, end],
  )
  const described = await toTransactions(q, rows, u.id)
  const closingCents = Number(u.balance_cents) - Number(after)
  let inCents = 0
  let outCents = 0
  const moves = rows.map((r) => (r.to_user_id === u.id ? Number(r.amount_cents) : -Number(r.amount_cents)))
  for (const c of moves) c >= 0 ? (inCents += c) : (outCents -= c)
  const openingCents = closingCents - inCents + outCents
  let balance = openingCents
  const lines = rows.map((r, i) => {
    balance += moves[i]
    return { at: r.created_at, reference: r.reference, description: described[i].description, cents: moves[i], balanceCents: balance }
  })
  return { from, to, openingCents, closingCents, inCents, outCents, lines }
}

